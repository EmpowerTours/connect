/**
 * `npm run protocol:abi`: regenerate src/lib/protocol/abi.ts from the Foundry build
 * (contracts/out, after `npm run contracts:test` or `forge build`). The app imports the
 * committed file, because the contracts folder is not part of the app image.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..");
const OUT = process.env.FORGE_OUT ?? path.join(ROOT, "contracts/out");
const names = ["ConnectGateway", "ConnectIdRegistry", "ConnectKeyRegistry"] as const;

let src = `/**\n * Generated by scripts/protocol-abi.ts from the Foundry build. Do not edit by hand;\n * run \`npm run protocol:abi\` after changing the contracts.\n */\n`;
for (const n of names) {
  const abi = (JSON.parse(readFileSync(path.join(OUT, `${n}.sol/${n}.json`), "utf8")) as { abi: unknown[] }).abi;
  const lower = n.replace("Connect", "");
  src += `\nexport const ${lower[0].toLowerCase()}${lower.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(path.join(ROOT, "src/lib/protocol/abi.ts"), src);
console.log("wrote src/lib/protocol/abi.ts");
